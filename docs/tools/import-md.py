#!/usr/bin/env python3
"""
Import a plain Markdown file into the docs site.

    python3 tools/import-md.py SOURCE.md SLUG [--title T] [--desc D] [--label L] [--order N] [--force]

    python3 tools/import-md.py ../docs/etc/troubleshooting.md deep-dives/troubleshooting \
        --label Troubleshooting --order 2

What it does to the file, and nothing else:
  * writes src/content/docs/SLUG.md with the frontmatter Starlight requires (title, description, sidebar)
  * drops the leading "# Heading" (Starlight prints the title itself) and a rule right after it
  * rewrites relative links to other pages ("../api/cell.md#x" -> "/api/cell/#x"), resolved against SLUG
  * wraps bare string ids in C++ blocks, `.id("x")` -> `.id(Id("x"))`, because the bare literal is ambiguous
  * keeps everything else byte for byte: code, tables, Mermaid diagrams, ASCII art

It never overwrites an existing page unless you pass --force. Afterwards:
  npm run dev                                   # look at it
  python3 tools/snippets.py check               # do its C++ blocks still compile?
"""
import argparse, posixpath, re, sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "src" / "content" / "docs"

def plain(md: str) -> str:
    md = re.sub(r"`([^`]*)`", r"\1", md)
    md = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", md)
    md = re.sub(r"[*_]{1,3}([^*_]+)[*_]{1,3}", r"\1", md)
    return re.sub(r"\s+", " ", md).strip()

def yaml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def fix_links(text: str, slug: str) -> str:
    here = posixpath.dirname(slug)
    def repl(m):
        label, target = m.group(1), m.group(2)
        if re.match(r"^[a-z]+:|^#|^/", target):
            return m.group(0)
        path, _, frag = target.partition("#")
        if not path.endswith(".md"):
            return m.group(0)
        resolved = posixpath.normpath(posixpath.join(here, path[:-3]))
        if resolved.endswith("/index"):
            resolved = resolved[: -len("/index")]
        return f"[{label}](/{resolved}/{('#' + frag) if frag else ''})"
    return re.sub(r"\[([^\]]*)\]\(([^)\s]+)\)", repl, text)

def fix_ids_in_cpp(text: str) -> str:
    def block(m):
        body = re.sub(r"\.id\(\"([^\"]*)\"\)", r'.id(Id("\1"))', m.group(2))
        return m.group(1) + body + m.group(3)
    return re.sub(r"(```(?:cpp|c\+\+)[^\n]*\n)(.*?)(^```)", block, text, flags=re.S | re.M)

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source"); ap.add_argument("slug")
    ap.add_argument("--title"); ap.add_argument("--desc"); ap.add_argument("--label")
    ap.add_argument("--order", type=int); ap.add_argument("--force", action="store_true")
    a = ap.parse_args()

    src = Path(a.source)
    if not src.is_file():
        sys.exit(f"error: {src} not found")
    slug = a.slug.strip("/").removesuffix(".md")
    dest = DOCS / f"{slug}.md"
    if dest.exists() and not a.force:
        sys.exit(f"error: {dest.relative_to(DOCS.parent.parent.parent)} exists (use --force to overwrite)")

    text = src.read_text(encoding="utf-8", errors="replace")
    if text.startswith("---\n"):                       # already has frontmatter: keep it, only fix links/ids
        body = fix_ids_in_cpp(fix_links(text, slug))
        dest.parent.mkdir(parents=True, exist_ok=True); dest.write_text(body, encoding="utf-8")
        print(f"wrote {dest} (frontmatter kept)"); return

    lines = text.splitlines()
    i = next((k for k, l in enumerate(lines) if l.strip()), 0)
    title = a.title
    if lines and lines[i].startswith("# "):
        h1 = lines[i][2:].strip(); title = title or plain(h1); del lines[i]
    title = title or slug.split("/")[-1].replace("-", " ").title()
    body = "\n".join(lines).lstrip("\n")
    body = re.sub(r"\A(?:[ \t]*\n)*---[ \t]*\n", "", body)           # rule right after the heading
    desc = a.desc
    if not desc:
        para = next((p for p in re.split(r"\n\s*\n", body) if p.strip() and not p.lstrip().startswith(("```", "#", ">", "|", "-", "*", "<"))), "")
        desc = plain(para)
        if len(desc) > 155:
            desc = desc[:155].rsplit(" ", 1)[0].rstrip(",.;:") + "…"
    side = []
    if a.label: side.append(f"  label: {yaml_str(a.label)}")
    if a.order is not None: side.append(f"  order: {a.order}")
    fm = f"---\ntitle: {yaml_str(title)}\ndescription: {yaml_str(desc)}\n" + ("sidebar:\n" + "\n".join(side) + "\n" if side else "") + "---\n\n"
    body = fix_ids_in_cpp(fix_links(body, slug))
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(fm + body.rstrip() + "\n", encoding="utf-8")
    print(f"wrote {dest}\n  title: {title}\n  sidebar: {'auto (folder is autogenerated)' if '/' in slug else 'add it to astro.config.mjs'}")

if __name__ == "__main__":
    main()
